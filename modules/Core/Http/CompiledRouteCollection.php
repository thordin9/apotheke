<?php

declare(strict_types=1);

namespace Apotheke\Core\Http;

use CodeIgniter\Router\RouteCollection;

/**
 * CI4's route collection, loaded from app/Config/RoutesCompiled.php instead of
 * running app/Config/Routes.php on every request (PLAN step 16 part 3). Building
 * about 140 routes through create() was the largest fixed cost of a CI4 request;
 * the compiled file is a plain array that opcache keeps.
 *
 * The compiled file names the xxh128 of the route files it came from. When they
 * differ (Routes.php edited, `php spark apotheke:routes` not run yet), or
 * when a route was added before loading (the test harness), this loads the
 * route files as CI4 does, so a stale file is never used. CompiledRoutesTest
 * fails when the committed file is out of date.
 */
class CompiledRouteCollection extends RouteCollection
{
    /** The properties loading the route files sets; anything else must stay as constructed. */
    public const PROPERTIES = ['routes', 'routesNames', 'routesOptions'];

    /** Whether loadRoutes() used the compiled file (tests). */
    protected bool $loadedFromCompiled = false;

    public static function compiledFile(): string
    {
        return APPPATH . 'Config/RoutesCompiled.php';
    }

    /** @param string $routesFile */
    public function loadRoutes(string $routesFile = APPPATH . 'Config/Routes.php')
    {
        if ($this->didDiscover) {
            return $this;
        }
        $compiled = $this->compiled($routesFile);
        if ($compiled === null) {
            return parent::loadRoutes($routesFile);
        }
        foreach (self::PROPERTIES as $property) {
            $this->{$property} = $compiled[$property];
        }
        $this->didDiscover = true;
        $this->loadedFromCompiled = true;

        return $this;
    }

    /** The source of RoutesCompiled.php for the current route files. */
    public function compile(string $routesFile = APPPATH . 'Config/Routes.php'): string
    {
        $fresh = new RouteCollection($this->fileLocator, $this->moduleConfig, config(\Config\Routing::class));
        $fresh->loadRoutes($routesFile);
        $data = ['hash' => $this->hash($routesFile)];
        foreach (self::PROPERTIES as $property) {
            $data[$property] = (fn (): array => $this->{$property})->call($fresh);
        }

        return "<?php\n\n// Generated by `php spark apotheke:routes` from app/Config/Routes.php. Do not edit.\n\nreturn "
            . var_export($data, true) . ";\n";
    }

    /** @return ?array<string,mixed> */
    private function compiled(string $routesFile): ?array
    {
        foreach (self::PROPERTIES as $property) {
            foreach ($this->{$property} as $list) {
                if ($list !== []) {
                    return null;
                }
            }
        }
        $file = self::compiledFile();
        if (!is_file($file)) {
            return null;
        }
        $data = require $file;
        if (!is_array($data) || ($data['hash'] ?? null) !== $this->hash($routesFile)) {
            return null;
        }

        return $data;
    }

    /** xxh128 of the route files CI4 would load, in its order. */
    private function hash(string $routesFile): string
    {
        $real = realpath($routesFile);
        $files = $this->routeFiles;
        $routesFile = $real === false ? $routesFile : $real;
        if (!in_array($routesFile, $files, true)) {
            $files[] = $routesFile;
        }
        $hashes = [];
        foreach ($files as $file) {
            $hashes[] = is_file($file) ? hash_file('xxh128', $file) : '-';
        }

        return hash('xxh128', implode("\n", $hashes));
    }
}
