<?php

declare(strict_types=1);

/**
 * Router for the PHP built-in server that tests/lib.php starts.
 * Static files and camera originals behave like ci4/public/router.php.
 * On the pgsql leg, after CI4 wires the connection, this checks the driver
 * is Postgre and inserts public.apotheke_ci4_pgsql_probe. Shipped boot does neither.
 */

if (!function_exists('ci4_test_arm_pgsql_probe')) {
    function ci4_test_arm_pgsql_probe(): void
    {
        static $armed = false;
        if ($armed || getenv('APOTHEKE_TEST_DB') !== 'pgsql') {
            return;
        }
        $armed = true;
        require_once dirname(__DIR__) . '/ci4/vendor/codeigniter4/framework/system/Events/Events.php';
        \CodeIgniter\Events\Events::on(
            'pre_system',
            static function (): void {
                ci4_test_pgsql_probe();
            },
            \CodeIgniter\Events\Events::PRIORITY_LOW
        );
    }

    function ci4_test_pgsql_probe(): void
    {
        try {
            $db = \Config\Database::connect();
        } catch (Throwable $e) {
            ci4_test_pgsql_fail('CI4 pgsql leg could not connect: ' . ci4_test_redact($e->getMessage()));
        }
        if ($db->DBDriver !== 'Postgre') {
            ci4_test_pgsql_fail('CI4 pgsql leg connected with ' . $db->DBDriver . ', expected Postgre');
        }
        $created = $db->query('CREATE TABLE IF NOT EXISTS public.apotheke_ci4_pgsql_probe (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)');
        $inserted = $db->query('INSERT INTO public.apotheke_ci4_pgsql_probe DEFAULT VALUES');
        if ($created === false || $inserted === false) {
            ci4_test_pgsql_fail('CI4 pgsql leg could not record public.apotheke_ci4_pgsql_probe');
        }
    }

    function ci4_test_pgsql_fail(string $log): never
    {
        if (PHP_SAPI !== 'cli') {
            http_response_code(500);
            header('Content-Type: text/plain; charset=UTF-8');
            echo 'Server error';
        }
        error_log($log);
        exit(1);
    }

    function ci4_test_redact(string $message): string
    {
        return preg_replace("/(password=)'(?:\\\\'|[^'])*'|(password=)\\S+/i", '$1$2***', $message) ?? $message;
    }
}

if (!function_exists('ci4_test_arm_wrong_ci4_password')) {
    /**
     * Test only. APOTHEKE_TEST_CI4_WRONG_PASSWORD gives CI4's own Postgre
     * connection a different password from the one the migration runner uses,
     * so the runner connects and CI4's lazy connect is refused.
     */
    function ci4_test_arm_wrong_ci4_password(): void
    {
        $wrong = getenv('APOTHEKE_TEST_CI4_WRONG_PASSWORD');
        if (!is_string($wrong) || $wrong === '') {
            return;
        }
        require_once dirname(__DIR__) . '/ci4/vendor/codeigniter4/framework/system/Events/Events.php';
        \CodeIgniter\Events\Events::on(
            'pre_system',
            static function () use ($wrong): void {
                $database = config(\Config\Database::class);
                $database->default['DSN'] = trim((string)($database->default['DSN'] ?? '')) . " password='" . addcslashes($wrong, "'\\") . "'";
            },
            \CodeIgniter\Events\Events::PRIORITY_LOW
        );
    }
}

if (!function_exists('ci4_test_arm_session_on_demand')) {
    /**
     * Test only. CI4 has no page with a form yet, which is what starts a session
     * on demand (SEC-L2). APOTHEKE_TEST_SESSION_ON_DEMAND=1 adds a required
     * before filter after `session` that asks for the CSRF token the way such a
     * page will, so the cookie tests can see a fresh session's Set-Cookie.
     */
    function ci4_test_arm_session_on_demand(): void
    {
        if (getenv('APOTHEKE_TEST_SESSION_ON_DEMAND') !== '1') {
            return;
        }
        require_once dirname(__DIR__) . '/ci4/vendor/codeigniter4/framework/system/Events/Events.php';
        \CodeIgniter\Events\Events::on(
            'pre_system',
            static function (): void {
                require_once __DIR__ . '/ci4-session-on-demand.php';
                $filters = config(\Config\Filters::class);
                $filters->aliases['testsessionondemand'] = \ApothekeTestSessionOnDemand::class;
                $filters->required['before'][] = 'testsessionondemand';
            },
            \CodeIgniter\Events\Events::PRIORITY_LOW
        );
    }
}

if (!function_exists('ci4_test_arm_html_page')) {
    /**
     * Test only. CI4 has no HTML page yet. APOTHEKE_TEST_HTML_PAGE=1 adds
     * GET /test-html-page, a text/html answer that prints base_url('labels'),
     * so the tests can see what an HTML response does to the session (#76
     * L-1) and which base URL CI4 builds (#76 L-2).
     */
    function ci4_test_arm_html_page(): void
    {
        if (getenv('APOTHEKE_TEST_HTML_PAGE') !== '1') {
            return;
        }
        require_once dirname(__DIR__) . '/ci4/vendor/codeigniter4/framework/system/Events/Events.php';
        \CodeIgniter\Events\Events::on(
            'pre_system',
            static function (): void {
                \Config\Services::routes()->get('test-html-page', static function (): string {
                    helper('url');

                    return '<!doctype html><title>test</title><p>' . htmlspecialchars(base_url('labels')) . '</p>';
                }, ['permission' => 'view']);
            },
            \CodeIgniter\Events\Events::PRIORITY_LOW
        );
    }
}

ci4_test_arm_pgsql_probe();
ci4_test_arm_wrong_ci4_password();
ci4_test_arm_session_on_demand();
ci4_test_arm_html_page();

return require dirname(__DIR__) . '/ci4/public/router.php';
