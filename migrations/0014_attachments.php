<?php
// 0014 – file attachments per item (receipts, manuals: PDF and images), stored under DATA_DIR/files with random names.
return static function (PDO $pdo, string $driver): void {
    $id = $driver === 'pgsql' ? 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'id INTEGER PRIMARY KEY AUTOINCREMENT';
    $pdo->exec("CREATE TABLE item_attachments (
        $id,
        item_id    INTEGER NOT NULL REFERENCES items(id) ON DELETE CASCADE,
        file       TEXT NOT NULL UNIQUE,
        name       TEXT NOT NULL,
        mime       TEXT NOT NULL,
        size       BIGINT NOT NULL,
        created_at TEXT NOT NULL
    )");
    $pdo->exec('CREATE INDEX idx_item_attachments_item ON item_attachments(item_id)');
};
