<?php
// 0029 – background jobs (API plan §3): CSV import commits, backup restores and backups run as a row here, and
// `php spark jobs:work` runs them one at a time. CI4 only (3.2.0 and later): 2.6.x ignores the table and a backup
// does not carry it. Every step is one statement guarded by status and lease_owner, so D1 needs no transaction.
return static function (PDO $pdo, string $driver): void {
    $id = $driver === 'pgsql' ? 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'id INTEGER PRIMARY KEY AUTOINCREMENT';
    $pdo->exec("CREATE TABLE jobs (
        $id,
        type         TEXT NOT NULL,
        status       TEXT NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'running', 'done', 'failed')),
        payload      TEXT NOT NULL,
        checkpoint   TEXT,
        result       TEXT,
        error        TEXT,
        attempts     INTEGER NOT NULL DEFAULT 0,
        max_attempts INTEGER NOT NULL DEFAULT 3,
        actor        TEXT,
        lease_owner  TEXT,
        lease_until  TEXT,
        run_after    TEXT NOT NULL,
        created_at   TEXT NOT NULL,
        updated_at   TEXT NOT NULL,
        started_at   TEXT,
        finished_at  TEXT
    )");
    $pdo->exec('CREATE INDEX idx_jobs_due ON jobs(status, run_after, id)');
};
