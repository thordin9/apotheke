<?php
// 0020 – CSV import history: one row per uploaded file (the file itself waits in DATA_DIR/tmp until it is imported).
// mapping = column index → field, options = {create, skip_errors}, result = counts once imported.
return static function (PDO $pdo, string $driver): void {
    $id = $driver === 'pgsql' ? 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'id INTEGER PRIMARY KEY AUTOINCREMENT';
    $pdo->exec("CREATE TABLE imports (
        $id,
        file_name   TEXT NOT NULL,
        status      TEXT NOT NULL,
        total_rows  INTEGER NOT NULL DEFAULT 0,
        mapping     TEXT NOT NULL,
        options     TEXT NOT NULL,
        result      TEXT,
        actor       TEXT,
        created_at  TEXT NOT NULL,
        finished_at TEXT
    )");
};
