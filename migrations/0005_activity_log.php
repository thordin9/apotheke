<?php
// 0005 – per-item activity log. item_id has no foreign key on purpose: entries outlive deleted items
// (item_name keeps the name for display). details is a JSON object.
return static function (PDO $pdo, string $driver): void {
    $id = $driver === 'pgsql' ? 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'id INTEGER PRIMARY KEY AUTOINCREMENT';
    $pdo->exec("CREATE TABLE activity (
        $id,
        item_id    INTEGER,
        item_name  TEXT NOT NULL,
        action     TEXT NOT NULL,
        details    TEXT NOT NULL DEFAULT '{}',
        created_at TEXT NOT NULL
    )");
    $pdo->exec('CREATE INDEX idx_activity_item ON activity(item_id, id)');
};
