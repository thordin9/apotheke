<?php
// 0004 – free-form tags (many-to-many) and custom fields: value (in cents), purchase date, serial number.
return static function (PDO $pdo, string $driver): void {
    $id = $driver === 'pgsql' ? 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'id INTEGER PRIMARY KEY AUTOINCREMENT';
    $pdo->exec("CREATE TABLE tags (
        $id,
        name       TEXT NOT NULL,
        name_key   TEXT NOT NULL UNIQUE,
        sort_key   TEXT NOT NULL DEFAULT '',
        created_at TEXT NOT NULL
    )");
    $pdo->exec('CREATE TABLE item_tags (
        item_id INTEGER NOT NULL REFERENCES items(id) ON DELETE CASCADE,
        tag_id  INTEGER NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
        PRIMARY KEY (item_id, tag_id)
    )');
    $pdo->exec('CREATE INDEX idx_item_tags_tag ON item_tags(tag_id)');
    $pdo->exec('ALTER TABLE items ADD COLUMN value_cents BIGINT');
    $pdo->exec('ALTER TABLE items ADD COLUMN purchase_date TEXT');
    $pdo->exec("ALTER TABLE items ADD COLUMN serial TEXT NOT NULL DEFAULT ''");
};
