<?php
// 0018 – user accounts with roles (admin / editor / viewer) replace the single shared password, and every history
// entry records who made the change. An existing password becomes the account "admin" (role admin), so the people who
// knew the password sign in with user name "admin" and the same password.
return static function (PDO $pdo, string $driver): void {
    $id = $driver === 'pgsql' ? 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'id INTEGER PRIMARY KEY AUTOINCREMENT';
    $pdo->exec("CREATE TABLE users (
        $id,
        username      TEXT NOT NULL,
        username_key  TEXT NOT NULL UNIQUE,
        password_hash TEXT NOT NULL,
        role          TEXT NOT NULL,
        created_at    TEXT NOT NULL,
        last_login_at TEXT
    )");
    $pdo->exec('ALTER TABLE activity ADD COLUMN actor TEXT');
    $set = $pdo->query("SELECT name, value FROM settings WHERE name IN ('auth_enabled', 'password_hash')")->fetchAll(PDO::FETCH_KEY_PAIR);
    $hash = json_decode((string)($set['password_hash'] ?? '""'), true);
    if (is_string($hash) && $hash !== '') {
        if (json_decode((string)($set['auth_enabled'] ?? 'false'), true) === true) {
            $pdo->prepare('INSERT INTO users (username, username_key, password_hash, role, created_at) VALUES (?,?,?,?,?)')
                ->execute(['admin', 'admin', $hash, 'admin', gmdate('Y-m-d H:i:s', app_time())]);
        }
        $pdo->prepare("UPDATE settings SET value = '\"\"' WHERE name = 'password_hash'")->execute();
    }
};
