<?php
// 0022 – configurable roles. The fixed admin / editor / viewer ranks become rows in `roles` with a list of granular
// permissions (see PERMISSIONS in src/roles.php); a fourth built-in role "guest" holds what visitors who are not
// signed in may do when guest browsing is allowed. Existing accounts keep their role key; an unknown key becomes viewer.
// Accounts get a status (active / pending – waiting for an admin to approve a self-registration), and auth_attempts
// rate-limits sign-in and registration per client address.
return static function (PDO $pdo, string $driver): void {
    $id = $driver === 'pgsql' ? 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'id INTEGER PRIMARY KEY AUTOINCREMENT';
    $pdo->exec("CREATE TABLE roles (
        $id,
        role_key   TEXT NOT NULL UNIQUE,
        name       TEXT NOT NULL,
        perms      TEXT NOT NULL,
        builtin    INTEGER NOT NULL DEFAULT 0,
        created_at TEXT NOT NULL
    )");
    $ins = $pdo->prepare('INSERT INTO roles (role_key, name, perms, builtin, created_at) VALUES (?,?,?,1,?)');
    foreach (ROLE_DEFAULTS as $key => [$name, $perms]) $ins->execute([$key, $name, json_encode($perms), gmdate('Y-m-d H:i:s', app_time())]);
    $pdo->exec("ALTER TABLE users ADD COLUMN status TEXT NOT NULL DEFAULT 'active'");
    $pdo->exec("UPDATE users SET role = 'viewer' WHERE role NOT IN ('admin', 'editor', 'viewer')");
    $pdo->exec("CREATE TABLE auth_attempts (
        $id,
        kind      TEXT NOT NULL,
        client    TEXT NOT NULL,
        at        INTEGER NOT NULL
    )");
    $pdo->exec('CREATE INDEX auth_attempts_k ON auth_attempts (kind, client, at)');
    settings_seed($pdo);
};
