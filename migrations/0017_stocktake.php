<?php
// 0017 – stocktakes: a check of one location (with its sub-locations). Each line is an item that was expected there
// (snapshot when the stocktake started) or that turned up there although it belongs elsewhere (misplaced).
return static function (PDO $pdo, string $driver): void {
    $id = $driver === 'pgsql' ? 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'id INTEGER PRIMARY KEY AUTOINCREMENT';
    $pdo->exec("CREATE TABLE stocktakes (
        $id,
        location_id   INTEGER REFERENCES locations(id) ON DELETE SET NULL,
        location_name TEXT NOT NULL,
        status        TEXT NOT NULL,
        started_at    TEXT NOT NULL,
        finished_at   TEXT,
        moves_applied INTEGER NOT NULL DEFAULT 0,
        summary       TEXT NOT NULL DEFAULT '{}'
    )");
    $pdo->exec('CREATE INDEX idx_stocktakes_status ON stocktakes(status, location_id)');
    $pdo->exec("CREATE TABLE stocktake_lines (
        $id,
        stocktake_id     INTEGER NOT NULL REFERENCES stocktakes(id) ON DELETE CASCADE,
        item_id          INTEGER REFERENCES items(id) ON DELETE SET NULL,
        item_name        TEXT NOT NULL,
        expected         INTEGER NOT NULL,
        home_location_id INTEGER,
        home_location    TEXT NOT NULL DEFAULT '',
        found            INTEGER NOT NULL DEFAULT 0,
        found_at         TEXT,
        moved            INTEGER NOT NULL DEFAULT 0
    )");
    $pdo->exec('CREATE UNIQUE INDEX idx_stocktake_lines_item ON stocktake_lines(stocktake_id, item_id)');
};
