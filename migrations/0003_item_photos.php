<?php
// 0003 – multiple photos per item. items.image stays as the cover (= photo at position 0) for fast lists;
// every existing single photo becomes that item's first photo.
return static function (PDO $pdo, string $driver): void {
    $id = $driver === 'pgsql' ? 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'id INTEGER PRIMARY KEY AUTOINCREMENT';
    $pdo->exec("CREATE TABLE item_photos (
        $id,
        item_id    INTEGER NOT NULL REFERENCES items(id) ON DELETE CASCADE,
        file       TEXT    NOT NULL,
        position   INTEGER NOT NULL DEFAULT 0,
        created_at TEXT    NOT NULL
    )");
    $pdo->exec('CREATE INDEX idx_item_photos_item ON item_photos(item_id, position)');
    $pdo->exec('INSERT INTO item_photos (item_id, file, position, created_at) SELECT id, image, 0, updated_at FROM items WHERE image IS NOT NULL');
};
