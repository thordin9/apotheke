<?php
// 0011 – saved filters: a named filter-sheet combination (search words, filters, sort) stored as a normalised query string.
return static function (PDO $pdo, string $driver): void {
    $id = $driver === 'pgsql' ? 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'id INTEGER PRIMARY KEY AUTOINCREMENT';
    $pdo->exec("CREATE TABLE saved_filters (
        $id,
        name       TEXT NOT NULL,
        name_key   TEXT NOT NULL UNIQUE,
        query      TEXT NOT NULL,
        sort_key   TEXT NOT NULL,
        created_at TEXT NOT NULL
    )");
};
