#!/usr/bin/env node
// The served asset bundle (plan §5 S1.1): `public/assets/` embedded in the Worker, with the cache key
// the PHP views print.
//
// A Worker has no filesystem, so the CSS, JS and icons travel inside the bundle. Embedding is what
// makes "byte-identical to `public/`" checkable: the base64 below *is* the file, and `test/html/
// assets.spec.ts` hashes what the Worker serves against `public/assets/` on disk.
//
// `version` is `substr(md5($mtime . $size), 0, 8)` from `modules/Core/Libraries/AssetUrl.php`, with
// the mtime pinned to 0. v3 derives it from the file's mtime, which differs per checkout; the golden
// fixture pins mtimes to 0 before rendering for the same reason, so both sides produce the same
// value from the same committed bytes. It is a cache key: it changes when the file's size does, and
// a change of the same size in the same second is the one case neither side catches.
//
// `npm run assets` writes the module; `npm run assets:check` (CI) fails when it is stale, the way
// `routes:check` does.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const ROOT = new URL("../", import.meta.url);
const SOURCE = new URL("../../public/assets/", import.meta.url);
const TARGET = new URL("src/assets/bundle.generated.ts", ROOT);

/** Everything a page or the web app manifest can point at; `autofill-sample.jpg` is documentation. */
const FILES = [
	"app.css",
	"app.js",
	"theme.js",
	"icon.svg",
	"favicon.svg",
	"favicon.ico",
	"apple-touch-icon.png",
	"icon-32.png",
	"icon-192.png",
	"icon-512.png",
	"icon-maskable-512.png",
	"mark.svg",
];

/** What the web server sends, matching the shipped image: CSS and JS with the charset the docs name. */
const CONTENT_TYPES = {
	css: "text/css; charset=utf-8",
	js: "text/javascript; charset=utf-8",
	svg: "image/svg+xml",
	png: "image/png",
	ico: "image/vnd.microsoft.icon",
};

const contentType = (name) => CONTENT_TYPES[name.split(".").pop()] ?? "application/octet-stream";

const build = () => {
	const rows = FILES.map((name) => {
		const bytes = readFileSync(new URL(name, SOURCE));
		return {
			name,
			contentType: contentType(name),
			size: bytes.length,
			// `AssetUrl::url()`: md5(mtime . size), mtime pinned to 0 for reproducibility.
			version: createHash("md5").update(`0${bytes.length}`).digest("hex").slice(0, 8),
			sha256: createHash("sha256").update(bytes).digest("hex"),
			base64: bytes.toString("base64"),
		};
	});
	return [
		"// Generated by `scripts/gen-assets.mjs` — do not edit. `npm run assets:check` fails when this",
		"// file and `public/assets/` disagree; the bytes are the file, base64 encoded.",
		"",
		"export interface BundledAsset {",
		"\treadonly name: string;",
		"\treadonly contentType: string;",
		"\treadonly size: number;",
		"\treadonly version: string;",
		"\treadonly sha256: string;",
		"\treadonly base64: string;",
		"}",
		"",
		"export const BUNDLE: readonly BundledAsset[] = [",
		...rows.map(
			(row) =>
				`\t{\n\t\tname: ${JSON.stringify(row.name)},\n\t\tcontentType: ${JSON.stringify(row.contentType)},\n\t\tsize: ${row.size},\n\t\tversion: ${JSON.stringify(row.version)},\n\t\tsha256: ${JSON.stringify(row.sha256)},\n\t\tbase64:\n\t\t\t${JSON.stringify(row.base64)},\n\t},`,
		),
		"];",
		"",
	].join("\n");
};

const generated = build();
const check = process.argv.includes("--check");

if (check) {
	let current;
	try {
		current = readFileSync(TARGET, "utf8");
	} catch {
		console.error("src/assets/bundle.generated.ts is missing: run `npm run assets`");
		process.exit(1);
	}
	if (current !== generated) {
		console.error("src/assets/bundle.generated.ts is stale: run `npm run assets` and commit the result");
		process.exit(1);
	}
	console.log(`Asset bundle is up to date: ${FILES.length} files`);
} else {
	writeFileSync(TARGET, generated);
	console.log(`Wrote src/assets/bundle.generated.ts: ${FILES.length} files`);
}
