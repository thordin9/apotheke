<?php

declare(strict_types=1);

namespace Apotheke\Core\Boot;

use Apotheke\Core\Config\ApothekeConfig;
use Apotheke\Core\Config\DatabaseFactory;
use Apotheke\Core\Config\DsnTranslator;
use Config\Database;
use Throwable;

/** Copies the translated DSN into CI4's default connection group before routing. */
final class FrameworkWiring
{
    public static function apply(): void
    {
        $config = ApothekeConfig::fromEnvironment();
        $group = (new DatabaseFactory($config, new DsnTranslator()))->group();
        $database = config(Database::class);
        $database->default = array_merge($database->default, $group);
        if (($group['DBDriver'] ?? '') === 'SQLite3') {
            $database->default['schema'] = '';
        }
        if (getenv('APOTHEKE_TEST_DB') === 'pgsql') {
            self::assertPgsqlLeg();
        }
    }

    /** The pgsql leg must be a real Postgre connection, and it leaves a row the job can count. */
    private static function assertPgsqlLeg(): void
    {
        try {
            $db = Database::connect();
        } catch (Throwable $e) {
            BootError::send('Server error', 'CI4 pgsql leg could not connect: ' . self::redact((string)$e->getMessage()));
        }
        $driver = $db->DBDriver;
        if ($driver !== 'Postgre') {
            BootError::send('Server error', 'CI4 pgsql leg connected with ' . $driver . ', expected Postgre');
        }
        $created = $db->query('CREATE TABLE IF NOT EXISTS public.apotheke_ci4_pgsql_probe (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)');
        $inserted = $db->query('INSERT INTO public.apotheke_ci4_pgsql_probe DEFAULT VALUES');
        if ($created === false || $inserted === false) {
            BootError::send('Server error', 'CI4 pgsql leg could not record public.apotheke_ci4_pgsql_probe');
        }
    }

    private static function redact(string $message): string
    {
        return preg_replace("/(password=)'(?:\\\\'|[^'])*'|(password=)\\S+/i", '$1$2***', $message) ?? $message;
    }
}
